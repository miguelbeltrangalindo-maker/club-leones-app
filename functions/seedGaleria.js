const now = admin.firestore.Timestamp.now();

async function seedCol(name, docs, buildFn){
  const existing = await db.collection(name).limit(1).get();
  if(!existing.empty && !FORCE){
    console.log(`⏭  "${name}" ya tiene documentos — omitido (usa --force para reescribir).`);
    return 0;
  }
  if(!APPLY){
    console.log(`🔍 DRY RUN "${name}": escribiría ${docs.length} documentos.`);
    return 0;
  }
  let written = 0;
  // Firestore batch: máx 500 ops
  for(let i=0; i<docs.length; i+=400){
    const batch = db.batch();
    docs.slice(i, i+400).forEach(d=>{
      const ref = db.collection(name).doc();
      batch.set(ref, buildFn(d));
    });
    await batch.commit();
    written += Math.min(400, docs.length - i);
  }
  console.log(`✅ "${name}": ${written} documentos escritos.`);
  return written;
}

(async () => {
  console.log(`\n${APPLY ? '⚙️  APLICANDO' : '🔍 DRY RUN'}${FORCE ? ' (FORCE)' : ''} — seed Galería Histórica\n`);
  console.log(`Presidentes: ${PRESIS.length} · Reinas: ${REINAS.length}\n`);

  await seedCol('presidentes', PRESIS, ([nombre, periodo]) => ({
    nombre, periodo, creadoEn: now, actualizadoEn: now, creadoPor: 'seed'
  }));
  await seedCol('reinas', REINAS, ([nombre, alias, periodo]) => ({
    nombre, periodo, alias: alias || null, creadoEn: now, actualizadoEn: now, creadoPor: 'seed'
  }));

  console.log('\n🏁 Listo.\n');
  process.exit(0);
})().catch(e => { console.error('✗ Error:', e); process.exit(1); });
